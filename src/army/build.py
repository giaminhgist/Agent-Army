"""Render army.toml + prompts/ into Claude Code agents, Codex agents and the `army` entry skill."""

from __future__ import annotations

import json
from pathlib import Path

from army import config

SKILL_DESCRIPTION = ("Agent-Army commander: plan a multi-step research/engineering goal and dispatch the army's "
                     "specialist sub-agents (scout, strategist, engineer, experimenter, writer, editor, reviewer, "
                     "auditor), with shared global/project memory.")

TIER_RULE = {
    "claude": ("Each agent has a default tier (light=sonnet, medium=opus, heavy=fable). Dispatch at the default; "
               "pass a higher `model` only when the task clearly needs deeper reasoning, and say why."),
    "codex": "Each agent runs at its fixed default tier; do not try to override the model when spawning.",
}
CROSS_MODEL_CMD = {
    "claude": '`codex exec --sandbox read-only "<brief>"`',
    "codex": '`claude -p --permission-mode plan "<brief>"`',
}
CROSS_MODEL_AGENTS = ("reviewer", "auditor")


COMMANDER_NOTE = {
    "claude": (" Start it with the /army skill. This agent file is only for running the commander as the main "
               "thread (`claude --agent army-commander`); as a sub-agent it cannot dispatch others."),
    "codex": (" Start it with the $army skill; as a spawned sub-agent it cannot dispatch others."),
}


def description(name: str, cfg: dict, platform: str) -> str:
    d = cfg["agents"][name]["description"]
    return d + COMMANDER_NOTE[platform] if name == "commander" else d


def agent_id(name: str, platform: str) -> str:
    return f"army-{name}" if platform == "claude" else f"army_{name}"


def _read(prompts_dir: Path, name: str) -> str:
    return (Path(prompts_dir) / f"{name}.md").read_text(encoding="utf-8").strip()


def skills_section(skills: list[str]) -> str:
    return ("## Skills\nRecommended skills (use when installed and relevant): " + ", ".join(skills) + ". "
            "Names may carry a plugin prefix (e.g. `superpowers:brainstorming`). If one is not installed, skip it. "
            "If the task needs a skill not on this list, look through the installed skills and use the one that fits.")


def agent_body(name: str, cfg: dict, prompts_dir: Path, platform: str) -> str:
    parts = [_read(prompts_dir, name).replace("{{TIER_RULE}}", TIER_RULE[platform]),
             _read(prompts_dir, "_protocol"),
             skills_section(cfg["agents"][name]["skills"])]
    if cfg.get("options", {}).get("cross_model_check") and name in CROSS_MODEL_AGENTS:
        parts.append(f"## Cross-model check\nFor important verdicts, also ask a different model: run "
                     f"{CROSS_MODEL_CMD[platform]} with a self-contained brief, and reconcile its findings with yours.")
    return "\n\n".join(parts) + "\n"


def _yaml_frontmatter(meta: dict) -> str:
    # JSON strings are valid YAML double-quoted scalars, so descriptions with ':' stay safe.
    return "---\n" + "".join(f"{k}: {json.dumps(v, ensure_ascii=False)}\n" for k, v in meta.items()) + "---\n"


def render_claude_agent(name: str, cfg: dict, prompts_dir: Path) -> str:
    a = cfg["agents"][name]
    meta = {"name": agent_id(name, "claude"), "description": description(name, cfg, "claude"),
            "model": config.tier_for(cfg, name, "claude")["model"], "tools": ", ".join(a["tools"])}
    return _yaml_frontmatter(meta) + "\n" + agent_body(name, cfg, prompts_dir, "claude")


def render_codex_agent(name: str, cfg: dict, prompts_dir: Path) -> str:
    a = cfg["agents"][name]
    tier = config.tier_for(cfg, name, "codex")
    lines = [f"# Generated by `army build` from army.toml — edit that file, not this one.",
             f"name = {json.dumps(agent_id(name, 'codex'))}",
             f"description = {json.dumps(description(name, cfg, 'codex'), ensure_ascii=False)}"]
    if tier["model"]:
        lines.append(f"model = {json.dumps(tier['model'])}")
    if tier["effort"]:
        lines.append(f"model_reasoning_effort = {json.dumps(tier['effort'])}")
    lines.append(f"developer_instructions = {json.dumps(agent_body(name, cfg, prompts_dir, 'codex'), ensure_ascii=False)}")
    return "\n".join(lines) + "\n"


def render_skill(cfg: dict, prompts_dir: Path, platform: str) -> str:
    rows = ["| Agent | Tier | Role |", "|---|---|---|"]
    for name in config.agent_names(cfg):
        if name == "commander":
            continue
        a = cfg["agents"][name]
        rows.append(f"| `{agent_id(name, platform)}` | {a['tier']} | {a['description']} |")
    how = ("Dispatch a specialist with the Agent tool, `subagent_type` = the agent name below."
           if platform == "claude" else
           "Spawn a specialist by naming it, e.g. \"have army_scout survey ...\".")
    body = "\n\n".join([
        "You are now acting as the Agent-Army commander for this conversation.",
        _read(prompts_dir, "commander").replace("{{TIER_RULE}}", TIER_RULE[platform]),
        "## The army\n" + how + "\n\n" + "\n".join(rows),
        _read(prompts_dir, "_protocol"),
        skills_section(cfg["agents"]["commander"]["skills"]),
    ])
    return _yaml_frontmatter({"name": "army", "description": SKILL_DESCRIPTION}) + "\n" + body + "\n"


def build_all(cfg: dict, prompts_dir: Path, out_dir: Path) -> dict[str, list[Path]]:
    out_dir = Path(out_dir)
    res: dict[str, list[Path]] = {"claude_agents": [], "codex_agents": [], "claude_skill": [], "codex_skill": []}
    for platform, ext, render in (("claude", "md", render_claude_agent), ("codex", "toml", render_codex_agent)):
        d = out_dir / platform / "agents"
        d.mkdir(parents=True, exist_ok=True)
        for name in config.agent_names(cfg):
            p = d / f"{agent_id(name, platform)}.{ext}"
            p.write_text(render(name, cfg, prompts_dir), encoding="utf-8")
            res[f"{platform}_agents"].append(p)
        sk = out_dir / platform / "skills" / "army" / "SKILL.md"
        sk.parent.mkdir(parents=True, exist_ok=True)
        sk.write_text(render_skill(cfg, prompts_dir, platform), encoding="utf-8")
        res[f"{platform}_skill"].append(sk)
    return res
